import 'package:hive/hive.dart';

part 'login_item.g.dart'; // This will be generated by build_runner

@HiveType(typeId: 0)
class LoginItem extends HiveObject {
  @HiveField(0)
  String title;

  @HiveField(1)
  String username;

  @HiveField(2)
  String password;

  @HiveField(3)
  String? firestoreId;

  LoginItem({
    required this.title,
    required this.username,
    required this.password,
    this.firestoreId,
  });

  String get type => 'Login';

  Map<String, dynamic> toJson() {
    return {
      'title': title,
      'username': username,
      'password': password,
    };
  }

  factory LoginItem.fromJson(Map<String, dynamic> json) {
    return LoginItem(
      title: json['title'] ?? '',
      username: json['username'] ?? '',
      password: json['password'] ?? '',
    );
  }
}

